class ArduinoSensing:
    def __init__(self, config):
        self.config = config
        self.ARDUINO_TEMPLATE = self.arduino_template()
        
    def arduino_template(self):
        ARDUINO_TEMPLATE = Template(r"""
        /*
        Generated by run_acq.py
        Multi-channel logger with:
        - sample-count-based calibration (fair per channel) + min time
        - READY -> wait 'S' -> START (150 ms cushion) handshake
        - elapsed t_ms since RUN start
        - single-line CSV: t_ms,<labels...>
        */

        #include <Arduino.h>

        // ====== PARAMS (generated) ======
        const float    VCC  = $VCCf;
        const float    VREF = VCC / 2.0f;

        const uint32_t DURATION_MS         = $DURATION_MS;
        const uint32_t CAL_TIME_MIN_MS     = $CAL_TIME_MIN_MS;
        const uint16_t CAL_SAMPLES_PER_CH  = $CAL_SAMPLES_PER_CH;

        const uint32_t SAMPLE_RATE_HZ      = $SAMPLE_RATE_HZ;
        const int      OVERSAMPLE          = $OVERSAMPLE;
        const bool     USE_SMOOTH          = $USE_SMOOTH;
        const float    ALPHA               = $ALPHAf;

        const uint8_t  CH_PINS[]           = { $CH_PINS };
        const char*    CH_LABELS[]         = { $CH_LABELS };
        const uint8_t  NCH                 = sizeof(CH_PINS)/sizeof(CH_PINS[0]);
        // =================================
                                    
        // ---- drift management ----
        const bool     USE_VCC_TRACK     = true;     // measure real VCC during run
        const uint16_t VCC_UPDATE_MS     = 1000;     // how often to refresh VCC (ms)
        const float    BASELINE_TAU_SEC  = 30.0f;    // HPF time constant (~30 s very slow)
        float          vcc_V             = VCC;      // current VCC in volts
        uint32_t       vcc_last_ms       = 0;
        float          baselineHP[6];                // slow baseline per channel
        float          betaHP            = 0.0f;     // IIR coefficient, computed in setup

        enum Phase { CAL, RUN, DONE };
        Phase phase = CAL;

        uint32_t next_us   = 0;
        uint32_t run_t0_ms = 0;
        uint32_t phase_t0_ms = 0;

        // storage (max 6 on Uno; we use NCH subset)
        float    baseline_counts[6];
        float    smoothV[6];
        uint32_t cal_sum[6];
        uint16_t cal_count[6];

        int readAvgCounts(uint8_t pin, int n) {
        long sum = 0;
        for (int i = 0; i < n; ++i) sum += analogRead(pin);
        return int((sum + n/2) / n);
        }
                                    
        // Measure AVcc (board 5V) using the internal 1.1 V bandgap
        long readVcc_mV() {
        // Select 1.1V (Vbg) as input, Vref = AVcc
        ADMUX = _BV(REFS0) | _BV(MUX3) | _BV(MUX2) | _BV(MUX1);
        delay(2);                            // wait Vbg to settle
        ADCSRA |= _BV(ADSC);                 // start conversion
        while (bit_is_set(ADCSRA, ADSC));    // wait
        uint16_t adc = ADC;
        // 1.1 V * 1023 * 1000 = 1125300
        return 1125300L / adc;               // mV
        }

        void setup() {
        pinMode(LED_BUILTIN, OUTPUT);
        digitalWrite(LED_BUILTIN, HIGH);
        analogReference(DEFAULT);
        Serial.begin($BAUD);
        delay(200);

        for (uint8_t ch=0; ch<NCH; ++ch) { baselineHP[ch]=0.0f; }
        const float Ts = 1.0f / float(SAMPLE_RATE_HZ);
        betaHP = 1.0f - expf(-Ts / BASELINE_TAU_SEC);   // very small (~1e-3)

        for (uint8_t ch=0; ch<NCH; ++ch) {
            baseline_counts[ch]=0; smoothV[ch]=0; cal_sum[ch]=0; cal_count[ch]=0;
        }
        phase_t0_ms = millis();
        }

        void loop() {
        if (phase == CAL) {
            // equal sample count per channel (no prints)
            for (uint8_t ch=0; ch<NCH; ++ch) {
            int avg = readAvgCounts(CH_PINS[ch], OVERSAMPLE);
            cal_sum[ch]   += (uint32_t)avg;
            cal_count[ch] += 1;
            }
            for (uint8_t ch=0; ch<NCH; ++ch) {
            if (cal_count[ch] > 0) {
                baseline_counts[ch] = float(cal_sum[ch]) / float(cal_count[ch]);
            }
            }
            bool enough = true;
            for (uint8_t ch=0; ch<NCH; ++ch) if (cal_count[ch] < CAL_SAMPLES_PER_CH) { enough=false; break; }

            if (enough && (millis() - phase_t0_ms) >= CAL_TIME_MIN_MS) {
            Serial.println(F("CALIBRATION DONE"));
            Serial.println(F("READY"));
            // wait for 'S' from PC
            while (Serial.available() == 0) { /* wait */ }
            while (Serial.available()) { if (Serial.read() == 'S') break; }
                                    
            //delay(500);

            run_t0_ms = millis();
            next_us   = micros();

            // CSV header
            Serial.print(F("t_ms"));
            for (uint8_t ch=0; ch<NCH; ++ch) { Serial.print(','); Serial.print(CH_LABELS[ch]); }
            Serial.println();

            phase = RUN;
            }
            return;
        }

        if (phase == RUN) {
            if (USE_VCC_TRACK && (millis() - vcc_last_ms) >= VCC_UPDATE_MS) {
                vcc_V = readVcc_mV() / 1000.0f;   // convert to volts
                vcc_last_ms = millis();
            }

            if (Serial.available()) {
                while (Serial.available()) {
                    if (Serial.read() == 'X') {
                    Serial.println(F("# ABORT"));
                    Serial.flush();
                    digitalWrite(LED_BUILTIN, LOW);
                    phase = DONE;
                    return;
                    }
                }
            }
                                    
            if ((millis() - run_t0_ms) >= DURATION_MS) {
            Serial.println(F("# DONE"));
            Serial.flush();
            digitalWrite(LED_BUILTIN, LOW);
            phase = DONE;
            return;
            }

            uint32_t now = micros();
            const uint32_t PERIOD_US = 1000000UL / SAMPLE_RATE_HZ;
            if ((int32_t)(now - next_us) >= 0) {
            float volts[6];
            for (uint8_t ch=0; ch<NCH; ++ch) {
                int counts = readAvgCounts(CH_PINS[ch], OVERSAMPLE);
                // counts difference -> volts using *measured* VCC
                float v = ((counts - baseline_counts[ch]) * (vcc_V / 1023.0f));

                // remove very-slow drift (high-pass with long tau)
                baselineHP[ch] += betaHP * (v - baselineHP[ch]);
                v -= baselineHP[ch];

                // optional fast smoothing (your EMA)
                if (USE_SMOOTH) { smoothV[ch] += ALPHA * (v - smoothV[ch]); v = smoothV[ch]; }

                volts[ch] = v;
            }

            uint32_t t_ms = millis() - run_t0_ms;
            Serial.print(t_ms);
            for (uint8_t ch=0; ch<NCH; ++ch) { Serial.print(','); Serial.print(volts[ch], 6); }
            Serial.println();

            next_us += PERIOD_US;
            }
            return;
        }

        delay(1000);
        }
        """)
        return ARDUINO_TEMPLATE

    def ensure_cli(self):
    # Make sure arduino-cli exists
        cli = self.config.ARDUINO_CLI
        try:
            subprocess.run([cli, "version"], check=True, capture_output=True)
        except Exception as e:
            print("ERROR: arduino-cli not found. Install and put it on PATH.")
            print("  https://arduino.github.io/arduino-cli/latest/installation/")
            sys.exit(1)
        return cli

    def gen_sketch_dir(self):
        sketch_dir = os.path.join(self.config.BASE_DIR, self.config.EXP_NAME)
        os.makedirs(sketch_dir, exist_ok=True)
        ino_path = os.path.join(sketch_dir, f"{self.config.EXP_NAME}.ino")
        return sketch_dir, ino_path

    def build_arduino_code(self):
        pins = ", ".join(p for p,_ in self.config.channels)
        labels = ", ".join(f"\"{lbl}\"" for _,lbl in self.config.channels)
        code = self.ARDUINO_TEMPLATE.substitute(
            VCCf=f"{self.config.VCC:.3f}",
            DURATION_MS=self.config.DURATION_MS,
            CAL_TIME_MIN_MS=self.config.CAL_TIME_MIN_MS,
            CAL_SAMPLES_PER_CH=self.config.CAL_SAMPLES_PER_CH,
            SAMPLE_RATE_HZ=self.config.SAMPLE_RATE_HZ,
            OVERSAMPLE=self.config.OVERSAMPLE,
            USE_SMOOTH=("true" if self.config.USE_SMOOTH else "false"),
            ALPHAf=f"{self.config.ALPHA:.3f}",
            CH_PINS=pins,
            CH_LABELS=labels,
            BAUD=self.config.BAUD,
        )
        return code
    
    def compile_upload(self, sketch_dir=None):
        cli = self.ensure_cli()
        fqbn = self.config.FQBN
        port = self.config.PORT
        if sketch_dir is None:
            sketch_dir = self.config.BASE_DIR
        print("Compiling…")
        r = subprocess.run([cli, "compile", "--fqbn", fqbn, sketch_dir])
        if r.returncode != 0:
            print("Compile failed.")
            sys.exit(1)
        print("Uploading…")
        r = subprocess.run([cli, "upload", "-p", port, "--fqbn", fqbn, sketch_dir])
        if r.returncode != 0:
            print("Upload failed.")
            sys.exit(1)
        print("Upload OK.")

    def calibrate_sensor(self, timeout_s=30.0):
        port = self.config.PORT
        baud = self.config.BAUD
        ser = serial.Serial(port, baud, timeout=0.005)

        # Clean reset starts the Arduino sketch and its CAL phase.
        ser.setDTR(False); time.sleep(0.2); ser.setDTR(True)
        ser.reset_input_buffer()

        print("Calibrating sensor. Please keep the network still.")
        t0 = time.perf_counter()
        while True:
            line = ser.readline().decode(errors="ignore").strip()
            if "READY" in line:
                print("Sensor calibration done; Arduino is READY.")
                return ser
            if line and "CALIBRATION DONE" not in line:
                print(line)
            if time.perf_counter() - t0 > timeout_s:
                ser.close()
                raise RuntimeError("Timeout waiting for READY")
            
    def start_sensing_run(self, ser):
        ser.write(b"S")
        ser.flush()
        return time.perf_counter()

    def wait_for_sensor_header(self, ser, timeout_s=5.0):
        t0 = time.perf_counter()
        while True:
            header = ser.readline().decode(errors="ignore").strip()
            if header.startswith("t_ms"):
                labels = header.split(",")
                labels[0] = "sensor_t_s"
                labels.insert(1, "host_t_s")
                return labels
            if time.perf_counter() - t0 > timeout_s:
                raise RuntimeError("Timeout waiting for CSV header")

    def acquire_started_run(self, ser, start_perf, outstem=None, live_plot=None, stop_event=None):
        if outstem is None:
            outstem = self.config.OUTPUT_STEM
        if live_plot is None:
            live_plot = self.config.LIVE_PLOT
        outstem = pathlib.Path(outstem)
        outstem.parent.mkdir(parents=True, exist_ok=True)

        labels = self.wait_for_sensor_header(ser)
        ncols = len(labels)

        if live_plot:
            plt.ion()
            fig, axs = plt.subplots(len(self.config.channels), 1, figsize=(10, 15), sharex=True)
            lines = []
            for i in range(2, ncols):
                ax = axs[i-2] if len(self.config.channels) > 1 else axs
                ax.set_title(f"Arduino A{i-2} - {labels[i]}")
                ax.set_ylabel("Voltage (V)")
                ax.grid(True)
                ax.set_xlim(-1, self.config.X_SECONDS+1)
                ax.set_ylim(self.config.Y_LIMS)
                ln, = ax.plot([], [], lw=1)
                lines.append(ln)
            axs[-1].set_xlabel("Time (s)")
            next_draw = time.perf_counter()

        buf = bytearray()
        sensor_t = []
        host_t = []
        ys = [[] for _ in range(ncols-2)]
        saw_done = False
        last_data = time.perf_counter()

        def process_row(s: str):
            nonlocal saw_done, last_data
            s = s.strip()
            if not s:
                return
            if s.startswith("#"):
                saw_done = True
                return
            if s.startswith("t_") or s == "READY":
                return
            parts = s.split(",")
            if len(parts) != ncols - 1:
                return
            try:
                t_ms = float(parts[0])
                vals = [float(x) for x in parts[1:]]
            except ValueError:
                return
            sensor_t.append(t_ms/1000.0)
            host_t.append(time.perf_counter() - start_perf)
            for i, v in enumerate(vals):
                ys[i].append(v)
            last_data = time.perf_counter()

        try:
            while True:
                n = ser.in_waiting
                if n:
                    buf += ser.read(n)
                    while True:
                        i = buf.find(b"\n")
                        if i < 0:
                            break
                        line = buf[:i]
                        if line.endswith(b"\r"):
                            line = line[:-1]
                        buf = buf[i+1:]
                        process_row(line.decode("utf-8", errors="ignore"))

                if live_plot and (not saw_done or time.perf_counter()-last_data < 0.3):
                    now = time.perf_counter()
                    if now >= next_draw:
                        if sensor_t:
                            for i, ln in enumerate(lines):
                                ln.set_data(sensor_t, ys[i])
                        fig = plt.gcf(); fig.canvas.draw(); fig.canvas.flush_events()
                        next_draw = now + 1.0/20.0

                if saw_done and (time.perf_counter()-last_data > 0.3) and ser.in_waiting == 0:
                    break
                if stop_event is not None and stop_event.is_set() and ser.in_waiting == 0:
                    break

                time.sleep(0.001)

        except KeyboardInterrupt:
            try:
                ser.write(b"X")
            except Exception:
                pass
            raise
        finally:
            try:
                ser.close()
            except Exception:
                pass

        csv_path = f"{outstem}/{self.config.EXP_NAME}_sensor.csv"
        with open(csv_path, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(labels)
            for i in range(len(sensor_t)):
                row = [f"{sensor_t[i]:.6f}", f"{host_t[i]:.6f}"] + [f"{ys[ch][i]:.6f}" for ch in range(ncols-2)]
                w.writerow(row)
        print(f"Saved sensor CSV: {csv_path}")

        if live_plot:
            plt.savefig(f"{outstem}/{self.config.EXP_NAME}_sensor.png", dpi=300)
            print(f"Saved sensor PNG: {outstem}/{self.config.EXP_NAME}_sensor.png")

        data = {"sensor_t_s": sensor_t, "host_t_s": host_t}
        for i, label in enumerate(labels[2:]):
            data[label] = ys[i]
        return pd.DataFrame(data)

    def run_and_log(self):
        port = self.config.PORT; baud = self.config.BAUD
        outstem = pathlib.Path(self.config.OUTPUT_STEM)
        outstem.parent.mkdir(parents=True, exist_ok=True)

        live_plot = self.config.LIVE_PLOT
        if live_plot:
            import matplotlib.pyplot as plt

        ser = serial.Serial(port, baud, timeout=0.005)

        # Clean reset (typical on Uno)
        ser.setDTR(False); time.sleep(0.2); ser.setDTR(True)

        # ---- Wait for READY, send 'S' ----
        t0 = time.time()
        while True:
            line = ser.readline().decode(errors="ignore").strip()
            if "READY" in line:
                ans = input("Calibration done. Run now? [y/N]: ").strip().lower()
                if ans.startswith("y"):
                    ser.write(b"S")
                    break
            if time.time() - t0 > 20:
                ser.close()
                raise RuntimeError("Timeout waiting for READY")

        # ---- Wait for the CSV header t_ms,... (robust to your 500 ms delay) ----
        t0 = time.time()
        while True:
            header = ser.readline().decode(errors="ignore").strip()
            if header.startswith("t_ms"):
                break
            if time.time() - t0 > 5:
                ser.close()
                raise RuntimeError("Timeout waiting for CSV header")
            # ignore blanks or stray lines

        labels = header.split(",")            # ['t_ms', 'pickup1', 'pickup2', ...]
        labels[0] = "t_s"  # change to seconds
        ncols  = len(labels)

        # ---- Plot setup ----
        if live_plot:
            plt.ion()
            fig, axs = plt.subplots(len(self.config.channels), 1, figsize=(10, 15), sharex=True)
            lines = []
            for i in range(1, ncols):
                ax = axs[i-1] if len(axs.shape) >= 1 else axs
                ax.set_title(f"Arduino A{i-1} - {labels[i]}")
                # ax.set_xlabel("Time (s)")
                ax.set_ylabel("Voltage (V)")
                ax.grid(True)
                # Remove static y-limits; will autoscale dynamically
                # ax.set_autoscale_on(True)
                ax.set_xlim(-1, self.config.X_SECONDS+1)  # keep x-limits static
                ax.set_ylim(self.config.Y_LIMS)
                # lines = [ax.plot([], [], lw=1, label=labels[i])[0] for i in range(1, ncols)]
                # ax.legend(loc="upper right")
                ln, = ax.plot([], [], lw=1)
                lines.append(ln)
            axs[-1].set_xlabel("Time (s)")
            next_draw = time.time()

        # ---- Chunked reader ----
        buf = bytearray()
        t = []
        ys = [[] for _ in range(ncols-1)]
        saw_done = False
        last_data = time.time()

        def process_row(s: str):
            nonlocal saw_done, last_data
            s = s.strip()
            if not s: return
            if s.startswith("#"):   # "# DONE" or "# ABORT"
                saw_done = True
                return
            if s.startswith("t_") or s == "READY":
                return
            parts = s.split(",")
            if len(parts) != ncols: return
            try:
                t_ms = float(parts[0])
                vals = [float(x) for x in parts[1:]]
            except ValueError:
                return
            t.append(t_ms/1000.0)
            for i,v in enumerate(vals): ys[i].append(v)
            last_data = time.time()

        try:
            while True:
                # fast, chunked read
                n = ser.in_waiting
                if n:
                    buf += ser.read(n)
                    while True:
                        i = buf.find(b"\n")
                        if i < 0: break
                        line = buf[:i]
                        if line.endswith(b"\r"): line = line[:-1]
                        buf = buf[i+1:]
                        process_row(line.decode("utf-8", errors="ignore"))

                # draw at fixed rate
                if live_plot and (not saw_done or time.time()-last_data < 0.3):
                    now = time.time()
                    if now >= next_draw:
                        if t:
                            for i,ln in enumerate(lines):
                                ln.set_data(t, ys[i])
                        fig = plt.gcf(); fig.canvas.draw(); fig.canvas.flush_events()
                        next_draw = now + 1.0/20.0

                # exit after '# DONE'/'# ABORT' and buffer quiet
                if saw_done and (time.time()-last_data > 0.3) and ser.in_waiting == 0:
                    break

                time.sleep(0.001)

        except KeyboardInterrupt:
            # User hit Ctrl-C -> tell Arduino to stop now
            try:
                ser.write(b"X")            # Arduino code will print "# ABORT" and stop
            except Exception:
                pass
            # give it a moment to finish
            end_t = time.time() + 1.0
            while time.time() < end_t:
                try:
                    chunk = ser.read(ser.in_waiting or 1)
                    if not chunk: time.sleep(0.01)
                except Exception:
                    break

        finally:
            try: ser.close()
            except: pass

        # ---- Save CSV (+ PNG if plotting) ----
        csv_path = f"{outstem}.csv"
        with open(csv_path, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(labels)
            for i in range(len(t)):
                row = [f"{t[i]:.6f}"] + [f"{ys[ch][i]:.6f}" for ch in range(ncols-1)]
                w.writerow(row)
        print(f"Saved CSV: {csv_path}")
        if self.config.LIVE_PLOT:
            import matplotlib.pyplot as plt
            plt.savefig(f"{outstem}.png", dpi=300)
            print(f"Saved PNG: {outstem}.png")